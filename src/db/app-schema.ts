import { index, integer, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core';
import { user } from './auth-schema'; // generated by `npm run auth:generate`

// Single row (id = 1). Admin-editable later; read per request.
export const settings = sqliteTable('settings', {
    id: integer('id').primaryKey(),
    openHour: integer('open_hour').notNull().default(9),
    closeHour: integer('close_hour').notNull().default(22), // exclusive: last slot starts at closeHour - 1
    hourlyRateSen: integer('hourly_rate_sen').notNull(),
    maxSlots: integer('max_slots').notNull().default(6),
    maxAttendees: integer('max_attendees').notNull(),
    leadMinutes: integer('lead_minutes').notNull().default(60),
});

export const bookings = sqliteTable(
    'bookings',
    {
        id: text('id').primaryKey(),
        ref: text('ref').notNull().unique(),
        userId: text('user_id').references(() => user.id, { onDelete: 'set null' }), // null = guest
        manageTokenHash: text('manage_token_hash'), // guest only; SHA-256 hex of the token
        guestName: text('guest_name').notNull(),
        guestEmail: text('guest_email').notNull(),
        guestPhone: text('guest_phone').notNull(),
        attendees: integer('attendees').notNull(),
        notes: text('notes'),
        startAt: text('start_at').notNull(), // 'YYYY-MM-DDTHH:00', MYT wall-clock
        endAt: text('end_at').notNull(), // exclusive
        status: text('status', { enum: ['pending', 'confirmed', 'cancelled'] })
            .notNull()
            .default('pending'),
        totalAmount: integer('total_amount').notNull(), // sen
        createdAt: integer('created_at', { mode: 'timestamp_ms' })
            .notNull()
            .$defaultFn(() => new Date()),
    },
    (t) => [
        uniqueIndex('bookings_token_hash_uq').on(t.manageTokenHash), // NULLs are allowed to repeat
        index('bookings_user_idx').on(t.userId),
        index('bookings_start_idx').on(t.startAt),
    ],
);

// The lock table: one row per occupied hour. PRIMARY KEY(slot) = the database
// refuses a double booking, no check-then-insert race.
export const occupiedSlots = sqliteTable('occupied_slots', {
    slot: text('slot').primaryKey(), // 'YYYY-MM-DDTHH:00'
    bookingId: text('booking_id').references(() => bookings.id, { onDelete: 'cascade' }),
    reason: text('reason'), // admin block-outs / buffers
});
